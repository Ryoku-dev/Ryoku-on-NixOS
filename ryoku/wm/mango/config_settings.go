// The settings.conf generator and the ini formatting helpers the block writers
// share. mango's config is `key=value` lines, `#` comments, colours as
// 0xrrggbbaa, booleans as 0/1. The store types live in config_store.go; the
// block writers in this file, config_binds.go and config_rules.go.

const confHeader = "# Generated by Ryoku Settings (Super + ,). Edit in the GUI, not here.\n\n"

// confBool renders 0/1.
func confBool(v bool) string {
	if v {
		return "1"
	}
	return "0"
}

// mangoColor normalises a stored #rrggbb (or bare rrggbbaa) to mango's
// 0xrrggbbaa spelling. Empty stays empty so the caller omits the line.
func mangoColor(hex string) string {
	h := strings.TrimSpace(hex)
	if h == "" {
		return ""
	}
	h = strings.TrimPrefix(h, "#")
	switch len(h) {
	case 6:
		h += "ff"
	case 8:
	default:
		return ""
	}
	for _, r := range h {
		if !strings.ContainsRune("0123456789abcdefABCDEF", r) {
			return ""
		}
	}
	return "0x" + strings.ToLower(h)
}

// confEnum drops the "default" sentinel: a string enum left at mango's own
// baseline writes no line, so mango's compiled default stands for it.
func confEnum(v string) string {
	if v == "default" {
		return ""
	}
	return v
}

// confNum formats a float plainly: mango parses %g output.
func confNum(f float64) string {
	return strconv.FormatFloat(f, 'g', -1, 64)
}

// line writes one key=value.
func line(b *strings.Builder, key, val string) {
	if val == "" {
		return
	}
	b.WriteString(key)
	b.WriteString("=")
	b.WriteString(val)
	b.WriteString("\n")
}

// genSettings renders settings.conf from the full effective store: the whole
// Ryoku look in mango's own key names. Additive blocks (env, autostart, rules)
// appear only when the store holds them, the same discipline niri's generator
// uses. The generated file is always written, empty included: the shipped entry
// sources it and apply must leave a complete, validating tree on disk.
func genSettings(s mangoStore) []byte {
	var b strings.Builder
	b.WriteString(confHeader)
	writeBehaviour(&b, s)
	writeAppearance(&b, s)
	writeAnimations(&b, s)
	writeInput(&b, s)
	writeCursor(&b, s.Cursor)
	writeLayout(&b, s)
	writeOverview(&b, s.Mango)
	writeScratchpad(&b, s.Mango)
	writeEnvironment(&b, s.Env)
	writeAutostart(&b, s.Autostart)
	writeWindowRules(&b, s)
	writeLayerRules(&b, s.Mango.LayerRules)
	return []byte(b.String())
}

