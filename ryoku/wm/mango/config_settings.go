// writeAppearance emits the frame, gaps, opacity, dim, shadow and blur block
// from the neutral desktop.appearance leaves.
func writeAppearance(b *strings.Builder, s mangoStore) {
	a := s.Appearance
	m := s.Mango
	line(b, "gappih", strconv.Itoa(a.GapsIn))
	line(b, "gappiv", strconv.Itoa(a.GapsIn))
	line(b, "gappoh", strconv.Itoa(a.GapsOut))
	line(b, "gappov", strconv.Itoa(a.GapsOut))
	line(b, "smartgaps", confBool(m.SmartGaps))
	line(b, "borderpx", strconv.Itoa(a.BorderSize))
	line(b, "border_radius", strconv.Itoa(a.Rounding))
	line(b, "no_border_when_single", confBool(m.NoBorderWhenSingle))
	line(b, "no_radius_when_single", confBool(m.NoRadiusWhenSingle))
	line(b, "focuscolor", mangoColor(a.ActiveBorder))
	line(b, "bordercolor", mangoColor(a.InactiveBorder))
	line(b, "urgentcolor", mangoColor(m.UrgentColor))
	line(b, "rootcolor", mangoColor(m.RootColor))
	line(b, "dropcolor", mangoColor(m.DropColor))
	line(b, "splitcolor", mangoColor(m.SplitColor))
	line(b, "maximizescreencolor", mangoColor(m.MaximizeColor))
	line(b, "scratchpadcolor", mangoColor(m.ScratchpadColor))
	line(b, "globalcolor", mangoColor(m.GlobalColor))
	line(b, "overlaycolor", mangoColor(m.OverlayColor))
	line(b, "focused_opacity", confNum(a.ActiveOpacity))
	line(b, "unfocused_opacity", confNum(a.InactiveOpacity))
	// The neutral dim model maps to mango's unfocused dim colour: strength
	// becomes the alpha of dim_unfocused_color, on when dimInactive is on.
	if a.DimInactive {
		line(b, "dim_enable", "1")
		line(b, "dim_focused_color", "0x00000000")
		line(b, "dim_unfocused_color", dimAlpha(a.DimStrength))
	} else {
		line(b, "dim_enable", "0")
		line(b, "dim_focused_color", "0x00000000")
		line(b, "dim_unfocused_color", "0x00000000")
	}
	if a.ShadowEnabled {
		line(b, "shadows", "1")
		line(b, "layer_shadows", "1")
		line(b, "shadow_only_floating", "0")
		line(b, "shadows_size", strconv.Itoa(a.ShadowRange))
		line(b, "shadows_blur", strconv.Itoa(maxInt(a.ShadowSpread*2, 1)))
		line(b, "shadows_position_x", strconv.Itoa(a.ShadowOffsetX))
		line(b, "shadows_position_y", strconv.Itoa(a.ShadowOffsetY))
		line(b, "shadowscolor", mangoColor(a.ShadowColor))
	} else {
		line(b, "shadows", "0")
		line(b, "layer_shadows", "0")
		line(b, "shadow_only_floating", "1")
	}
	if a.BlurEnabled {
		line(b, "blur", "1")
		line(b, "blur_layer", "1")
		line(b, "blur_optimized", "1")
		line(b, "blur_params_radius", strconv.Itoa(a.BlurSize))
		line(b, "blur_params_num_passes", strconv.Itoa(a.BlurPasses))
		line(b, "blur_params_noise", confNum(a.BlurNoise))
		line(b, "blur_params_saturation", confNum(a.BlurVibrancy))
		line(b, "blur_params_brightness", "0.9")
		line(b, "blur_params_contrast", "0.9")
	} else {
		line(b, "blur", "0")
		line(b, "blur_layer", "0")
	}
	b.WriteString("\n")
}

// dimAlpha turns the neutral 0..1 dim strength into mango's 0x000000AA colour:
// only the alpha channel matters for the dim node.
func dimAlpha(strength float64) string {
	if strength < 0 {
		strength = 0
	}
	if strength > 1 {
		strength = 1
	}
	a := int(strength*255 + 0.5)
	return "0x000000" + hexByte(a)
}

func hexByte(n int) string {
	const digits = "0123456789abcdef"
	return string([]byte{digits[(n>>4)&0xf], digits[n&0xf]})
}

// writeAnimations emits the animation master switch and the per-event type,
// duration and curve block from the wm.mango.anim tree. Mode "default" emits
// nothing for that event so mango's own baseline stands; "off" zeroes the
// duration, which mango reads as no animation for the event.
func writeAnimations(b *strings.Builder, s mangoStore) {
	a := s.Appearance
	m := s.Mango
	line(b, "animations", confBool(a.Animations))
	line(b, "layer_animations", confBool(a.Animations))
	writeAnim(b, "open", m.Anim.Open)
	writeAnim(b, "close", m.Anim.Close)
	writeAnim(b, "move", m.Anim.Move)
	writeAnim(b, "tag", m.Anim.Tag)
	line(b, "animation_fade_in", confBool(a.Animations))
	line(b, "animation_fade_out", confBool(a.Animations))
	line(b, "fadein_begin_opacity", confNum(m.FadeinBeginOpacity))
	line(b, "fadeout_begin_opacity", confNum(m.FadeoutBeginOpacity))
	line(b, "zoom_initial_ratio", confNum(m.ZoomInitialRatio))
	line(b, "zoom_end_ratio", confNum(m.ZoomEndRatio))
	line(b, "tag_animation_direction", m.TagAnimationDirection)
	line(b, "layer_animation_type_open", confEnum(m.LayerAnimationTypeOpen))
	line(b, "layer_animation_type_close", confEnum(m.LayerAnimationTypeClose))
	b.WriteString("\n")
}

func writeAnim(b *strings.Builder, event string, spec AnimSpec) {
	if spec.Mode == "default" || spec.Mode == "" {
		return
	}
	if spec.Mode == "off" {
		line(b, "animation_duration_"+event, "0")
		return
	}
	if spec.Type != "" {
		line(b, "animation_type_"+event, spec.Type)
	}
	if spec.DurationMs > 0 {
		line(b, "animation_duration_"+event, strconv.Itoa(spec.DurationMs))
	}
	if spec.Curve != "" {
		line(b, "animation_curve_"+event, spec.Curve)
	}
}

