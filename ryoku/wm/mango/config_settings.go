// accelProfile maps the neutral "flat"|"none" onto mango's 0/1/2. Empty means
// the device default, which is adaptive (2) on mango's own default.
func accelProfile(p string) string {
	switch p {
	case "flat":
		return "1"
	case "none":
		return "0"
	default:
		return "2"
	}
}

// clickMethod maps the neutral clickfinger flag onto mango's 1/2.
func clickMethod(clickfinger bool) string {
	if clickfinger {
		return "2"
	}
	return "1"
}

