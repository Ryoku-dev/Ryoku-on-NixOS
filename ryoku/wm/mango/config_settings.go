// writeEnvironment emits the store's env= lines. mango's env values reset on
// reload, so they live in the generated file (which reload re-sources) rather
// than only in the seed: one writer, and the value survives every reload.
func writeEnvironment(b *strings.Builder, env []EnvVar) {
	if len(env) == 0 {
		return
	}
	for _, e := range env {
		if e.Key == "" {
			continue
		}
		line(b, "env", e.Key+","+e.Value)
	}
	b.WriteString("\n")
}

// writeAutostart emits the store's autostart commands as exec-once lines. The
// shipped session bootstrap lives in autostart.conf; these are the user's own
// additions from the Hub, so they are additive and only appear when set.
func writeAutostart(b *strings.Builder, cmds []Autostart) {
	if len(cmds) == 0 {
		return
	}
	for _, a := range cmds {
		if strings.TrimSpace(a.Command) == "" {
			continue
		}
		line(b, "exec-once", a.Command)
	}
	b.WriteString("\n")
}

func maxInt(a, b int) int {
	if a > b {
		return a
	}
	return b
}

// seededLayouts is the loaded keyboard-layout list for the bar indicator. mango's
// IPC answers only the ACTIVE layout name, never the set, so the set comes from
// the generated tree (xkb_rules_layout, comma-separated).
func seededLayouts() []string {
	for _, name := range []string{"settings.conf", "keyboard.conf"} {
		b, err := os.ReadFile(filepath.Join(mangoConfigDir(), name))
		if err != nil {
			continue
		}
		for _, raw := range strings.Split(string(b), "\n") {
			k, v, ok := strings.Cut(strings.TrimSpace(raw), "=")
			if !ok || k != "xkb_rules_layout" {
				continue
			}
			var out []string
			for _, tok := range strings.Split(v, ",") {
				if t := strings.TrimSpace(tok); t != "" {
					out = append(out, strings.TrimSpace(t))
				}
			}
			if len(out) > 0 {
				return out
			}
		}
	}
	return nil
}

// configScalarInt reads one integer scalar from the live generated config,
// falling back to def when the file or key is absent. mango answers no getter
// over IPC, so the tree on disk is the record of the current value.
func configScalarInt(key string, def int) int {
	b, err := os.ReadFile(filepath.Join(mangoConfigDir(), "settings.conf"))
	if err != nil {
		return def
	}
	for _, raw := range strings.Split(string(b), "\n") {
		k, v, ok := strings.Cut(strings.TrimSpace(raw), "=")
		if !ok || k != key {
			continue
		}
		if n, err := strconv.Atoi(strings.TrimSpace(v)); err == nil {
			return n
		}
		return def
	}
	return def
}

// rewriteTagLayout pins one tag's layout by regenerating settings.conf with the
// tag's tagrule rewritten, then reloading the running session. The tagrule set
// is generated in full every apply, so this edits the tree, not the store.
func rewriteTagLayout(ws, layout string) error {
	dir := mangoConfigDir()
	b, err := os.ReadFile(filepath.Join(dir, "settings.conf"))
	if err != nil {
		return err
	}
	want := "tagrule=id:" + ws + ","
	out := make([]string, 0, 48)
	hit := false
	for _, raw := range strings.Split(string(b), "\n") {
		trimmed := strings.TrimSpace(raw)
		if strings.HasPrefix(trimmed, want) && strings.Contains(trimmed, "layout_name:") {
			fields := strings.Split(trimmed[len(want):], ",")
			edited := false
			for i, f := range fields {
				if strings.HasPrefix(f, "layout_name:") {
					fields[i] = "layout_name:" + layout
					edited = true
				}
			}
			if !edited {
				fields = append(fields, "layout_name:"+layout)
			}
			out = append(out, want+strings.Join(fields, ","))
			hit = true
			continue
		}
		out = append(out, raw)
	}
	if !hit {
		out = append(out, want+"layout_name:"+layout)
	}
	body := []byte(strings.Join(out, "\n"))
	if err := atomicWrite(filepath.Join(userEditsMangoDir(), "settings.conf"), body, 0o644); err != nil {
		return err
	}
	if err := atomicWrite(filepath.Join(dir, "settings.conf"), body, 0o644); err != nil {
		return err
	}
	return dispatch("reload_config")
}
