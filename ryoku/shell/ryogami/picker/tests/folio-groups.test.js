"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const layout = {};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,"../qml/folio/FolioLayout.js"),"utf8"),layout);
const toggle={id:"neutralStyle",kind:"toggle"};
const brightness={id:"surfaceBrightness",kind:"number",group:"surfaces"};
const tint={id:"cardTint",kind:"number",group:"surfaces"};
const accents={id:"accentLinks",kind:"toggle",group:"accents"};
const section={groups:[{id:"surfaces",title:"Surfaces"},{id:"accents",title:"Accents"}],controls:[toggle,brightness,tint,accents]};
const rows=layout.buildRows(section);
assert.deepEqual(Array.from(rows,r=>r.type),["control","group","control","control","group","control"]);
assert.equal(rows[0].group,"");
assert.equal(rows[1].title,"Surfaces");
assert.equal(rows[2].control,brightness);
assert.equal(rows[2].group,"surfaces");
assert.equal(rows[3].group,"surfaces");
assert.equal(rows[5].group,"accents");
assert.equal(section.controls.length,4,"search retains the original flat controls");
assert.equal(layout.buildRows({controls:[toggle]}).length,1,"other sections remain unchanged");
assert.equal(layout.buildRows({controls:[{id:"unknown",group:"absent"} ]})[0].group,"","undefined groups never hide controls");
console.log("PASS: folio dropdown groups preserve controls and leave other sections unchanged");
